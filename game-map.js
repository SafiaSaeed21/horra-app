// OPEN CITY CHALLENGE (Starts at Question 1 of 5)
function openCityChallenge(cityKey) {
  const cityData = citiesDatabase[cityKey];
  if (!cityData) {
    console.error("City not found in database:", cityKey);
    return;
  }

  currentCityKey = cityKey;
  currentQuestionIndex = 0;

  modalCityIconEl.textContent = cityData.icon;
  modalCityTitleEl.textContent = `${cityData.title}`;

  renderCurrentQuestion();

  mapCityModalEl.classList.add("active");
}

// Helper: Shuffle array randomly (Fisher-Yates)
function shuffleArray(array) {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function renderCurrentQuestion() {
  const cityData = citiesDatabase[currentCityKey];
  if (!cityData || !cityData.questions) return;

  const currentQ = cityData.questions[currentQuestionIndex];

  modalStep1El.classList.remove("hidden");
  modalStep1El.classList.add("active");
  modalStep2El.classList.add("hidden");
  modalStep3El.classList.add("hidden");

  modalLandmarkImgEl.src = currentQ.image;
  modalQuestionTextEl.textContent = `السؤال (${currentQuestionIndex + 1} من 5): ${currentQ.question}`;

  modalOptionsGridEl.innerHTML = "";

  // SHUFFLE OPTIONS RANDOMIZED SO CORRECT OPTION IS NEVER ALWAYS FIRST!
  const shuffledOptions = shuffleArray(currentQ.options);

  shuffledOptions.forEach((opt) => {
    const btn = document.createElement("button");
    btn.className = "city-opt-btn";
    btn.textContent = opt.text;
    btn.onclick = () => handleAnswerChoice(opt.correct, btn);
    modalOptionsGridEl.appendChild(btn);
  });
}

function handleAnswerChoice(isCorrect, btnElement) {
  const cityData = citiesDatabase[currentCityKey];

  if (isCorrect) {
    btnElement.classList.add("correct-opt");
    playSoundEffect("correct");

    // Disable all options
    const allBtns = modalOptionsGridEl.querySelectorAll(".city-opt-btn");
    allBtns.forEach(b => b.disabled = true);

    setTimeout(() => {
      if (currentQuestionIndex < cityData.questions.length - 1) {
        currentQuestionIndex++;
        renderCurrentQuestion();
      } else {
        // Complete all 5 questions! Show Reward Step!
        showCityCompletionStep();
      }
    }, 1200);

  } else {
    btnElement.classList.add("wrong-opt");
    playSoundEffect("wrong");
  }
}

function showCityCompletionStep() {
  const cityData = citiesDatabase[currentCityKey];

  modalStep1El.classList.add("hidden");
  modalStep2El.classList.add("hidden");
  modalStep3El.classList.remove("hidden");
  modalStep3El.classList.add("active");

  modalFactTextEl.textContent = `مبارك يا مستكشف! أجبت عن كافة الأسئلة الـ 5 لـ ${currentCityKey} بنجاح! 💡 المعلومة الاستكشافية: ${cityData.questions[4].fact}`;
  playSoundEffect("win");
}

function claimCityStamp() {
  if (currentCityKey) {
    unlockedCitiesSet.add(currentCityKey);
    updatePassportStampsUI();
  }
  closeCityModal();
}

function closeCityModal() {
  if (mapCityModalEl) {
    mapCityModalEl.classList.remove("active");
  }
}

function updatePassportStampsUI() {
  const passportSlots = document.querySelectorAll(".passport-slot");
  let unlockedCount = 0;

  passportSlots.forEach(slot => {
    const city = slot.getAttribute("data-city");
    if (unlockedCitiesSet.has(city)) {
      unlockedCount++;
      slot.classList.add("unlocked-stamp");
      const lockIcon = slot.querySelector(".slot-lock");
      if (lockIcon) lockIcon.textContent = "⭐ ختم";
    }
  });

  const percent = Math.round((unlockedCount / 16) * 100);
  if (mapProgressLabelEl) {
    mapProgressLabelEl.textContent = `تحرير الخريطة: ${unlockedCount} من 16 (${percent}%)`;
  }
}

function playSoundEffect(type) {
  try {
    const audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    const osc = audioCtx.createOscillator();
    const gain = audioCtx.createGain();
    osc.connect(gain);
    gain.connect(audioCtx.destination);

    if (type === "correct") {
      osc.frequency.setValueAtTime(523.25, audioCtx.currentTime); // C5
      osc.frequency.setValueAtTime(659.25, audioCtx.currentTime + 0.1); // E5
      gain.gain.setValueAtTime(0.2, audioCtx.currentTime);
      osc.start();
      osc.stop(audioCtx.currentTime + 0.25);
    } else if (type === "win") {
      osc.frequency.setValueAtTime(523.25, audioCtx.currentTime);
      osc.frequency.setValueAtTime(659.25, audioCtx.currentTime + 0.15);
      osc.frequency.setValueAtTime(783.99, audioCtx.currentTime + 0.3); // G5
      gain.gain.setValueAtTime(0.3, audioCtx.currentTime);
      osc.start();
      osc.stop(audioCtx.currentTime + 0.5);
    } else {
      osc.frequency.setValueAtTime(220, audioCtx.currentTime);
      gain.gain.setValueAtTime(0.2, audioCtx.currentTime);
      osc.start();
      osc.stop(audioCtx.currentTime + 0.2);
    }
  } catch (e) {}
}
